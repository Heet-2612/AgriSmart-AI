/** Alphabetically sorted list of all available Indian States & UTs */
export const INDIAN_STATES: string[] = Object.keys(INDIAN_DISTRICTS_BY_STATE).sort((a, b) =>
  a.localeCompare(b)
);

/**
 * Get alphabetically sorted list of districts for a given state name
 */
export function getDistrictsForState(state: string): string[] {
  if (!state) return [];
  // Case-insensitive state lookup
  const matchedKey = Object.keys(INDIAN_DISTRICTS_BY_STATE).find(
    (s) => s.toLowerCase() === state.trim().toLowerCase()
  );
  if (!matchedKey) return [];
  return [...INDIAN_DISTRICTS_BY_STATE[matchedKey]].sort((a, b) => a.localeCompare(b));
}

/**
 * Filter states based on case-insensitive query (prefix matches prioritized, partial matches supported)
 */
export function searchStates(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return INDIAN_STATES;

  const prefixMatches: string[] = [];
  const substringMatches: string[] = [];

  for (const state of INDIAN_STATES) {
    const sLower = state.toLowerCase();
    if (sLower.startsWith(q)) {
      prefixMatches.push(state);
    } else if (sLower.includes(q)) {
      substringMatches.push(state);
    }
  }

  return [...prefixMatches.sort((a, b) => a.localeCompare(b)), ...substringMatches.sort((a, b) => a.localeCompare(b))];
}

/**
 * Filter districts for a state based on case-insensitive query
 */
export function searchDistricts(state: string, query: string): string[] {
  const districts = getDistrictsForState(state);
  const q = query.trim().toLowerCase();
  if (!q) return districts;

  const prefixMatches: string[] = [];
  const substringMatches: string[] = [];

  for (const district of districts) {
    const dLower = district.toLowerCase();
    if (dLower.startsWith(q)) {
      prefixMatches.push(district);
    } else if (dLower.includes(q)) {
      substringMatches.push(district);
    }
  }

  return [...prefixMatches.sort((a, b) => a.localeCompare(b)), ...substringMatches.sort((a, b) => a.localeCompare(b))];
}

/**
 * Validate whether a district belongs to a state
 */
export function isValidDistrictForState(state: string, district: string): boolean {
  if (!state || !district) return false;
  const districts = getDistrictsForState(state);
  return districts.some((d) => d.toLowerCase() === district.trim().toLowerCase());
}
